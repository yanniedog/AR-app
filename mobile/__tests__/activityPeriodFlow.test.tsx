import React from 'react';
import mockReact from 'react';
import TestRenderer, { act } from 'react-test-renderer';
import { ActivityPeriodCalculation } from '../src/components/product/ActivityPeriodCalculation';
import { activityHarness, activityInputs } from '../test-support/activityHarness';
import { ActivityEvents } from '../src/components/product/ActivityEvents';
import { profile as mockProfile } from '../test-support/executableDepositHarness';
import * as Clipboard from 'expo-clipboard';
import { Decimal } from '../src/lib/productTermsEngine/decimal';
let mockState: any;
jest.mock('../src/data/store', () => ({ useStore: (selector: any) => selector(mockState) }));
jest.mock('../src/data/payload', () => ({ downloadInflate: jest.fn() }));
jest.mock('../src/hooks/useCustomerProfile', () => ({ useCustomerProfile: () => ({ profile: mockProfile, busy: false }) }));
jest.mock('../src/components/CustomerProfilePanel', () => ({ CustomerAnswerEditor: 'CustomerAnswerEditor' }));
jest.mock('../src/components/ledger/LedgerField', () => ({ LedgerField: 'LedgerField' }));
jest.mock('../src/components/product/DepositCriteria', () => ({ ReviewedCriteria: 'ReviewedCriteria' }));
jest.mock('../src/components/ui', () => ({ AppText: 'AppText', Row: 'Row', Button: 'Button', Chip: 'Chip', Disclosure: ({ children, open, ...props }: any) => mockReact.createElement('Disclosure', props, open ? children : null) }));
jest.mock('expo-clipboard', () => ({ setStringAsync: jest.fn(async () => undefined) }));

test('lazy private savings form calculates, exports, and invalidates on input or edition change', async () => {
  const h = await activityHarness(); mockState = { ...h.context, ensureDetails: jest.fn(async () => undefined) };
  let tree: any; await act(async () => { tree = TestRenderer.create(<ActivityPeriodCalculation productKey={h.target.productKey} />); });
  expect(tree.root.findAllByProps({ title: 'Calculate' })).toHaveLength(0);
  await act(async () => tree.root.findByProps({ title: 'Prior activity' }).props.onToggle());
  const choose = tree.root.findAllByType('Chip')[0];
  act(() => choose.props.onPress());
  for (const [label, value] of [['Local account reference','local-test'],['Opening balance (AUD)','1000.25'],['Period start · Included','2026-01-01'],['Period end · Excluded','2026-01-11']]) act(() => tree.root.findByProps({ label }).props.onChangeText(value));
  const rate = tree.root.findAllByType('LedgerField').find((n: any) => n.props.label.startsWith('Confirmed annual rate'));
  expect(rate.props.label).toContain('Marginal tier'); expect(JSON.stringify(tree.toJSON())).toContain('3.65%');
  act(() => rate.props.onChangeText('3.65'));
  const bonusFields = tree.root.findAllByType('LedgerField').filter((n:any)=>n.props.label.startsWith('Bonus annual rate'));
  bonusFields.forEach((field:any,index:number)=>act(()=>field.props.onChangeText(Decimal.parse(h.subject.policy.bonus.tiers[index].annualRate).mul(Decimal.parse('100')).fixed(10))));
  act(()=>tree.root.findByProps({label:'Coverage complete'}).props.onPress());
  for (const label of ['Opening accrual zero','Opening funds cleared','No movements','No withholding','Confirm details']) act(() => tree.root.findByProps({ label }).props.onPress());
  act(() => tree.root.findByProps({ title: 'Calculate' }).props.onPress());
  expect(JSON.stringify(tree.toJSON())).toContain('1001.25');
  await act(async () => tree.root.findByProps({ title: 'Copy receipt' }).props.onPress());
  const receipt = JSON.parse((Clipboard.setStringAsync as jest.Mock).mock.calls.at(-1)[0]);
  expect(receipt.adapterInputs.inputs.openingBalance).toBe('1000.25'); expect(receipt.receipt.claimAvailable).toBe(true);expect(receipt.receipt.ledger[0].savingsContributions[1].status).toBe('does_not_meet');
  const displayed = () => tree.root.findAllByType('AppText').map((node: any) => String(node.props.children));
  expect(displayed()).toContain('Qualifying withdrawals: 0 · ');
  const deposit = activityInputs.activity.events[0];
  act(() => tree.root.findByType(ActivityEvents).props.onChange([deposit, ...['Withdrawal.1', 'Withdrawal.2'].map(id => ({ ...deposit, id, kind: 'withdrawal', amount: '1' }))]));
  expect(tree.root.findAllByProps({ title: 'Copy receipt' })).toHaveLength(0);
  act(() => tree.root.findByProps({ label: 'Confirm details' }).props.onPress());
  act(() => tree.root.findByProps({ title: 'Calculate' }).props.onPress());
  expect(displayed()).toContain('Qualifying deposits: $100.25 · ');
  expect(displayed()).toContain('Qualifying withdrawals: 2 · ');
  expect(displayed().some((text: string) => text.includes('Qualifying withdrawals: $'))).toBe(false);
  await act(async () => tree.root.findByProps({ title: 'Copy receipt' }).props.onPress());
  const updated = JSON.parse((Clipboard.setStringAsync as jest.Mock).mock.calls.at(-1)[0]);
  const metrics = updated.receipt.ledger[0].savingsContributions[1].activityResults;
  expect(metrics.find((metric: any) => metric.field === 'activity_withdrawal_count').fact).toEqual({ type: 'decimal', value: '2', unit: 'count' });
  expect(metrics.find((metric: any) => metric.field === 'activity_deposit_total').fact).toEqual({ type: 'decimal', value: '100.25', unit: 'AUD' });
  act(() => tree.root.findByProps({ label: 'Opening balance (AUD)' }).props.onChangeText('2000'));
  expect(tree.root.findAllByProps({ title: 'Copy receipt' })).toHaveLength(0);
  mockState = { ...mockState, manifest: { ...mockState.manifest } }; delete mockState.manifest.executable_v4;
  await act(async () => tree.update(<ActivityPeriodCalculation productKey={h.target.productKey} />));
  expect(JSON.stringify(tree.toJSON())).toContain('Unavailable');
});
