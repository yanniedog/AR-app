/* global __dirname, Buffer */
/* Reproducible standalone producer compiler. No npm installation is needed at its destination. */
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const { createRequire, builtinModules } = require('node:module');
const ts = require('typescript');
const root = path.resolve(__dirname, '..');
const modules = new Map();
const sourceFiles = {};
const digest = value => crypto.createHash('sha256').update(value).digest('hex');
const readSource = file => fs.readFileSync(file, 'utf8').replaceAll('\r\n', '\n');
const compare = (a, b) => a < b ? -1 : a > b ? 1 : 0;
const idOf = file => path.relative(root, file).replaceAll('\\', '/');
function visit(file) {
  const id = idOf(file);
  if (modules.has(id)) return id;
  modules.set(id, null);
  const source = readSource(file);
  sourceFiles[id] = digest(source);
  if (file.endsWith('.json')) { modules.set(id, `module.exports=${source.trim()};`); return id; }
  let code = source;
  if (/\.tsx?$/.test(file)) code = ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.CommonJS, esModuleInterop: true } }).outputText;
  // Synchronous imports only: the compiler never calls the app's async UI helpers.
  const tree = ts.createSourceFile(file, code, ts.ScriptTarget.Latest, true, ts.ScriptKind.JS);
  const imports = new Set();
  for (const statement of tree.statements) {
    function walk(node) {
      if (ts.isFunctionLike(node)) return;
      if (ts.isCallExpression(node) && ts.isIdentifier(node.expression) && node.expression.text === 'require' && node.arguments.length === 1 && ts.isStringLiteral(node.arguments[0])) imports.add(node.arguments[0].text);
      ts.forEachChild(node, walk);
    }
    walk(statement);
  }
  const mapping = {};
  for (const spec of imports) {
    if (spec.startsWith('node:') || builtinModules.includes(spec)) { mapping[spec] = spec; continue; }
    let resolved;
    if (spec.startsWith('.')) {
      const base = path.resolve(path.dirname(file), spec);
      resolved = [base, `${base}.ts`, `${base}.tsx`, `${base}.js`, `${base}.json`, path.join(base, 'index.ts'), path.join(base, 'index.js')].find(candidate => fs.existsSync(candidate) && fs.statSync(candidate).isFile());
    } else resolved = createRequire(file).resolve(spec);
    if (!resolved) throw new Error(`Unresolved ${id}: ${spec}`);
    mapping[spec] = visit(resolved);
  }
  modules.set(id, `const require=s=>load(${JSON.stringify(mapping)}[s]??s);\n${code}`);
  return id;
}
const entry = visit(path.join(root, 'src/data/historicalBankRateReadyCompiler.ts'));
const wire = visit(path.join(root, 'src/data/historicalBankRateReadyWire.ts'));
// Consumer semantics are part of the pin, even though the producer does not execute them.
for (const name of ['src/data/historicalBankRateReady.ts', 'scripts/export-history-ready-compiler.cjs']) sourceFiles[name] = digest(readSource(path.join(root, name)));
const manifestSources = Object.fromEntries(Object.entries(sourceFiles).sort(([a], [b]) => compare(a, b)));
const bundle = `'use strict';\n// Generated by scripts/export-history-ready-compiler.cjs.\n// Sources: ${JSON.stringify(manifestSources)}\nconst nativeRequire=require;\nconst modules={\n${[...modules].sort(([a], [b]) => compare(a, b)).map(([id, code]) => `${JSON.stringify(id)}:(module,exports,load)=>{\n${code}\n}`).join(',\n')}\n};\nconst cache=new Map();\nfunction load(id){if(!modules[id]){if(id.startsWith('node:')||nativeRequire('node:module').builtinModules.includes(id))return nativeRequire(id);throw Error('Unavailable compiler dependency: '+id);}if(cache.has(id))return cache.get(id).exports;const module={exports:{}};cache.set(id,module);modules[id](module,module.exports,load);return module.exports;}\nconst compiler=load(${JSON.stringify(entry)}),wire=load(${JSON.stringify(wire)});\nmodule.exports={compile:compiler.compileHistoricalBankRateReady,validateReady:wire.validateHistoricalBankRateReady};\nif(require.main===module){try{const fs=require('node:fs'),crypto=require('node:crypto');const ownSha=crypto.createHash('sha256').update(fs.readFileSync(__filename)).digest('hex');const validating=process.argv.includes('--validate');const input=fs.readFileSync(0);if(input.length>(validating?4*1024*1024:128*1024*1024))throw Error('Compiler input exceeds budget');const value=JSON.parse(input.toString('utf8'));let result;if(validating){if(!module.exports.validateReady(value,ownSha))throw Error('Invalid ready history');result={valid:true};}else result=module.exports.compile(value,ownSha);const output=JSON.stringify(result);if(Buffer.byteLength(output)>4*1024*1024)throw Error('Ready history exceeds decoded budget');process.stdout.write(output);}catch(error){process.stderr.write(String(error)+'\\n');process.exitCode=1;}}\n`;
const sha = digest(bundle);
const destination = path.join(root, 'contracts/history-ready');
fs.mkdirSync(destination, { recursive: true });
const outputs = { 'compiler.cjs': bundle, 'compiler-manifest.json': `${JSON.stringify({ sha256: sha, compiler_sha256: sha, semantic_revision: 'ar-history-ready-v1', source_files: manifestSources }, null, 2)}\n` };
for (const [name, content] of Object.entries(outputs)) {
  const file = path.join(destination, name);
  if (process.argv.includes('--check')) {
    if (fs.readFileSync(file, 'utf8').replaceAll('\r\n', '\n') !== content) throw new Error(`Stale ready compiler artifact: ${name}`);
  } else fs.writeFileSync(file, content);
}
process.stdout.write(`${sha} ${Buffer.byteLength(bundle)} bytes\n`);
