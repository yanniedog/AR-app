type IssueCode = typeof REVIEWED_ISSUE_CODES[number];
export type ReceiptFactTopic = 'calculation' | 'fees' | 'deposit' | 'savings' | 'activity' | 'loan' | 'portfolio' | 'eligibility' | 'source' | 'scope' | 'rate' | 'rounding' | 'applicability' | 'material-terms' | 'fee-inventory' | 'fee-timing' | 'fee-waiver' | 'fee-ordering' | 'payment-allocation' | 'payment-obligation' | 'business-calendar' | 'posting-calendar' | 'payment-destination' | 'tax-treatment' | 'break-fee' | 'principal-recovery' | 'bonus-qualification' | 'projected-payments' | 'missing-input' | 'invalid-input';
export type ReceiptFactState = 'unknown' | 'unverified' | 'unsupported' | 'unavailable' | 'needs_information' | 'does_not_meet' | 'unpaid' | 'partial' | 'acknowledged' | 'source-review-required';
export interface ReceiptIssueFact { readonly index: number; readonly topic: ReceiptFactTopic; readonly state: ReceiptFactState; readonly code: IssueCode | ScopedIssueCode | null; readonly references: readonly string[] }
export interface ReceiptCriterionFact { readonly ruleId: string; readonly state: 'needs_information' | 'does_not_meet'; readonly field: string | null; readonly inputState: 'missing' | 'invalid' | 'unresolved'; readonly references: readonly string[] }
const id = (value: string) => /^[A-Za-z0-9_./:@+\-=]{1,180}$/.test(value);
const common: Readonly<Record<string, ReceiptFactTopic>> = {
  fee_inventory_not_proven: 'fee-inventory', fee_inventory_incomplete: 'fee-inventory',
  fee_ordering_unknown: 'fee-ordering', fee_waiver_unknown: 'fee-waiver',
  fee_timing_unknown: 'fee-timing', loan_allocation_unknown: 'payment-allocation',
  loan_projected_executions_assumption: 'projected-payments',
  td_business_calendar_unknown: 'business-calendar', td_posting_calendar_unknown: 'posting-calendar',
  td_payment_destination_unknown: 'payment-destination', td_tax_treatment_unknown: 'tax-treatment',
  td_break_fee_decision_unknown: 'break-fee', td_principal_recovery_decision_unknown: 'principal-recovery',
};
function topic(code: IssueCode): ReceiptFactTopic {
  if (common[code]) return common[code];
  return code.startsWith('fee_') ? 'fees' : code.startsWith('td_') ? 'deposit' : code.startsWith('savings_') ? 'savings'
    : code.startsWith('activity_') || code.startsWith('preceding_activity_') ? 'activity' : code.startsWith('loan_') ? 'loan'
    : code.startsWith('portfolio_') ? 'portfolio' : code.startsWith('source_') ? 'source'
    : code.startsWith('rate_') ? 'rate' : code.startsWith('rounding_') ? 'rounding' : 'calculation';
}
