type ScopedIssueCode = keyof typeof scoped;
const scopedCode = (value: string): value is ScopedIssueCode => Object.hasOwn(scoped, value);
const reviewed: Readonly<Record<string, ReceiptFactTopic>> = { applicability: 'applicability', materialTerms: 'material-terms', feeCoverage: 'fees', rateSchedule: 'rate' };
export function receiptIssueFacts(receipt: CalculationReceipt): readonly ReceiptIssueFact[] {
  const qualificationReferences = new Map<string, readonly string[]>();
  for (const entry of receipt.ledger) for (const contribution of entry.savingsContributions ?? []) {
    qualificationReferences.set(`savings_qualification_unknown:${contribution.intervalId}:${contribution.componentId}`, [contribution.intervalId, contribution.componentId]);
  }
  return receipt.issues.map((raw, index) => {
    const parts = raw.split(':'), prefix = parts[0], refs = parts.slice(1);
    const scopedRefs = scopedCode(prefix) && scoped[prefix][1] === 1 ? [raw.slice(prefix.length + 1)] : qualificationReferences.get(raw) ?? refs;
    const exact = REVIEWED_ISSUE_CODES.find(code => code === raw);
    let result: ReceiptIssueFact = { index, topic: 'calculation', state: 'source-review-required', code: null, references: [] };
    if (exact) result = { index, topic: topic(exact), state: exact.includes('unknown') ? 'unknown' : exact.includes('unverified') ? 'unverified' : 'unavailable', code: exact, references: [] };
    else if (prefix === 'unverified' && refs.length === 1 && Object.hasOwn(reviewed, refs[0])) result = { index, topic: reviewed[refs[0]], state: 'unverified', code: null, references: [] };
    else if (prefix === 'eligibility' && refs.length === 1 && (refs[0] === 'needs_information' || refs[0] === 'does_not_meet')) result = { index, topic: 'eligibility', state: refs[0], code: null, references: [] };
    else if (scopedCode(prefix) && scopedRefs.length === scoped[prefix][1] && scopedRefs.every(id)) result = {
      index, topic: scoped[prefix][0], state: prefix === 'loan_obligation_unpaid' ? 'unpaid' : prefix === 'loan_obligation_partial' ? 'partial' : 'unknown', code: prefix, references: scopedRefs,
    };
    else if (prefix === 'unsupported_term' && id(raw.slice(prefix.length + 1))) result = { index, topic: 'scope', state: 'unsupported', code: null, references: [raw.slice(prefix.length + 1)] };
    else if (prefix === 'fee_price_unknown' && id(raw.slice(prefix.length + 1))) result = { index, topic: 'fees', state: 'unknown', code: null, references: [raw.slice(prefix.length + 1)] };
    const acknowledged = result.code === 'loan_projected_executions_assumption' && receipt.issueDetails?.find(detail =>
      detail.kind === 'acknowledged_assumption' && detail.index === index && detail.code === raw && id(detail.assumptionId));
    return acknowledged ? { ...result, state: 'acknowledged', references: [acknowledged.assumptionId] } : result;
  });
}
export function receiptAssumptionFacts(receipt: CalculationReceipt): readonly ReceiptIssueFact[] {
  return receipt.assumptions.map((value, index) => ({ index, topic: value === 'loan_projected_executions_assumption' ? 'projected-payments' : 'calculation',
    state: 'source-review-required', code: value === 'loan_projected_executions_assumption' ? value : null, references: [] }));
}
export function receiptCriterionFacts(receipt: CalculationReceipt): readonly ReceiptCriterionFact[] {
  const facts: ReceiptCriterionFact[] = [], seen = new Set<string>();
  function visit(trace: RuleTrace, references: readonly string[], depth = 0) {
    if (depth > 16 || facts.length >= 512) return;
    if (trace.children?.length) { trace.children.forEach(child => visit(child, references, depth + 1)); return; }
    if (trace.status !== 'needs_information' && trace.status !== 'does_not_meet') return;
    const match = /^(missing|invalid):([^:]+)$/.exec(trace.reason ?? '');
    const field = match && id(match[2]) ? match[2] : null;
    const key = JSON.stringify([trace.id, trace.status, field, references]);
    if (seen.has(key)) return; seen.add(key);
    facts.push({ ruleId: trace.id, state: trace.status, field, inputState: field ? match![1] === 'missing' ? 'missing' : 'invalid' : 'unresolved', references });
  }
  if (receipt.eligibility) visit(receipt.eligibility.trace, []);
  for (const entry of receipt.ledger) {
    for (const trace of entry.feeRuleTraces ?? []) visit(trace, [entry.id]);
    for (const contribution of entry.savingsContributions ?? []) if (contribution.qualification) visit(contribution.qualification.trace, [contribution.intervalId, contribution.componentId]);
  }
  return facts;
}
